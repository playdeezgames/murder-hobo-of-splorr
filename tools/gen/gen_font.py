#!/usr/bin/env python3
"""Generates odin/game/font_data.odin from the original's CyFont5x7.json (the game's UIFont, 6x8 cells, ASCII 32..127)."""
import json, os
root = os.path.join(os.path.dirname(__file__), "..", "..")
data = json.load(open(os.path.join(root, "src/MHOS/Content/Fonts/CyFont5x7.json")))
height = data["Height"]
glyphs = data["Glyphs"]
chars = [chr(c) for c in range(32, 128)]
assert set(chars) == set(glyphs), "font no longer covers exactly ASCII 32..127"
widths = {glyphs[c]["Width"] for c in chars}
assert widths == {6} and height == 8, "the renderer assumes a fixed 6 by 8 cell"
rows = []
for c in chars:
    r = [0] * height
    for y, xs in glyphs[c]["Lines"].items():
        for x in xs:
            assert 0 <= x < 6 and 0 <= int(y) < height
            r[int(y)] |= 1 << x
    rows.append(r)
out = ["package game", "", "// GENERATED by tools/gen/gen_font.py from src/MHOS/Content/Fonts/CyFont5x7.json. Do not edit.", "",
       f"FONT_WIDTH :: {6}", f"FONT_HEIGHT :: {height}", "FONT_FIRST :: 32 // the glyph of ASCII 32 is index 0", f"FONT_COUNT :: {len(chars)}", "",
       "// One byte per pixel row; bit x is the pixel in column x (bit 0 is the leftmost).", "FONT_ROWS :: [FONT_COUNT][FONT_HEIGHT]u8{"]
for c, r in zip(chars, rows):
    out.append("\t{" + ", ".join(f"0x{b:02X}" for b in r) + "}, // " + (repr(c) if c != "\x7f" else "DEL"))
out.append("}")
open(os.path.join(root, "odin/game/font_data.odin"), "w").write("\n".join(out) + "\n")
print("wrote odin/game/font_data.odin")
