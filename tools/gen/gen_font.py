#!/usr/bin/env python3
"""Generates odin/game/font_data.odin and tools/vb-oracle/m5x7.json from odin/assets/m5x7.ttf (needs Pillow).

The font is proportional: ASCII 32..126 each with an advance (ink plus one pixel of spacing, from the font itself), 9 pixel rows
(7 above the baseline, 2 below). ASCII 127 is a blank. The JSON is in the format of the original game's font files, so the VB game
(the oracle) can draw with the same font."""
import json, os
from PIL import Image, ImageDraw, ImageFont

root = os.path.join(os.path.dirname(__file__), "..", "..")
font = ImageFont.truetype(os.path.join(root, "odin/assets/m5x7.ttf"), 16)
HEIGHT, ABOVE = 9, 7
chars = [chr(c) for c in range(32, 127)]
glyphs = []
for c in chars:
    advance = int(font.getlength(c))
    img = Image.new("L", (advance, HEIGHT), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = "1"
    d.text((0, ABOVE), c, font=font, fill=255, anchor="ls")
    rows = []
    for y in range(HEIGHT):
        bits = 0
        for x in range(advance):
            if img.getpixel((x, y)) > 127:
                bits |= 1 << x
        rows.append(bits)
    assert advance <= 8 and all(r < 256 for r in rows), (c, advance)
    glyphs.append((c, advance, rows))
glyphs.append(("\x7f", 5, [0] * HEIGHT))  # DEL: a blank the width of a space

out = ["package game", "", "// GENERATED by tools/gen/gen_font.py from odin/assets/m5x7.ttf (m5x7 by Daniel Linssen, CC0). Do not edit.", "",
       f"FONT_HEIGHT :: {HEIGHT}", "FONT_FIRST :: 32 // the glyph of ASCII 32 is index 0", f"FONT_COUNT :: {len(glyphs)}", "",
       "// Pixels from the left edge to the next glyph (the ink plus one pixel of spacing).", "FONT_ADVANCE :: [FONT_COUNT]u8{"]
out.append("\t" + ", ".join(str(a) for _, a, _ in glyphs) + ",")
out += ["}", "", "// One byte per pixel row; bit x is the pixel in column x (bit 0 is the leftmost).", "FONT_ROWS :: [FONT_COUNT][FONT_HEIGHT]u8{"]
for c, _, r in glyphs:
    out.append("\t{" + ", ".join(f"0x{b:02X}" for b in r) + "}, // " + (repr(c) if c != "\x7f" else "DEL"))
out.append("}")
open(os.path.join(root, "odin/game/font_data.odin"), "w").write("\n".join(out) + "\n")

js = {"Height": HEIGHT, "Glyphs": {}}
for c, a, rows in glyphs:
    lines = {str(y): [x for x in range(a) if rows[y] >> x & 1] for y in range(HEIGHT) if rows[y]}
    js["Glyphs"][c] = {"Width": a, "Lines": lines}
json.dump(js, open(os.path.join(root, "tools/vb-oracle/m5x7.json"), "w"), indent=1)
print("wrote odin/game/font_data.odin and tools/vb-oracle/m5x7.json")
